// FormatNextSteps returns guidance after init-cra runs.
func FormatNextSteps(category string) string {
	var sb strings.Builder
	sb.WriteString("\nNext steps:\n")
	sb.WriteString("  1. Review and customize .chainsaw.yaml\n")
	sb.WriteString("  2. Run 'chainsaw comply' to see your baseline CRA score\n")
	sb.WriteString("  3. Run 'chainsaw check' to see all findings\n")

	switch category {
	case "important-class-1", "important-class-2":
		sb.WriteString("  4. Prepare conformity self-assessment (EU-type examination for Class II)\n")
		sb.WriteString("  5. Monitor Notified Body availability (deadline: 2026-06-11)\n")
	case "critical":
		sb.WriteString("  4. Engage a Notified Body for third-party conformity assessment\n")
		sb.WriteString("  5. Monitor Notified Body designation (deadline: 2026-06-11)\n")
	default:
		sb.WriteString("  4. Prepare manufacturer self-assessment documentation\n")
	}

	sb.WriteString("  5. Set up vulnerability reporting workflow (deadline: 2026-09-11)\n")
	return sb.String()
}
